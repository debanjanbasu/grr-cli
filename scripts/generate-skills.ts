// ———————————————————————————— Write / check ————————————————————————————

/** Remove generated skill directories for services the index no longer
 * lists. Only directories containing a file with our marker are touched. */
async function pruneStaleSkills(validServices: Set<string>, dryRun: boolean): Promise<string[]> {
  const removed: string[] = [];
  const entries = await readdir(SKILLS_DIR, { withFileTypes: true }).catch(() => []);
  for (const entry of entries) {
    if (!entry.isDirectory() || validServices.has(entry.name) || entry.name === 'grr') continue;
    const file = resolve(SKILLS_DIR, entry.name, 'SKILL.md');
    const content = await readFile(file, 'utf8').catch(() => null);
    if (content === null || !content.includes(MARKER)) continue; // never touch foreign files
    if (!dryRun) await rm(resolve(SKILLS_DIR, entry.name), { recursive: true });
    removed.push(entry.name);
  }
  return removed;
}

const relPath = (path: string): string => path.slice(ROOT.length + 1).replaceAll('\\', '/');

async function main(): Promise<void> {
  const manifest = JSON.parse(await readFile(MANIFEST, 'utf8')) as Manifest;
  const services = await loadIndex();
  const analyses = services.map(analyze);
  const totalMethods = analyses.reduce((sum, a) => sum + a.service.methods.length, 0);

  const targets: Array<{ path: string; content: string }> = [];
  for (const a of analyses) {
    targets.push({
      path: resolve(SKILLS_DIR, a.service.name, 'SKILL.md'),
      content: skillMarkdown(a, manifest.generatedAt),
    });
  }
  targets.push({ path: resolve(SKILLS_DIR, 'README.md'), content: readmeMarkdown(analyses, manifest.generatedAt) });

  if (CHECK_ONLY) {
    const stale: string[] = [];
    for (const target of targets) {
      // Line-ending-independent compare: Windows runners check out with
      // CRLF (autocrlf) while the generator writes LF — see the matching
      // note in generate-commands.ts.
      const previous = (await readFile(target.path, 'utf8').catch(() => null))?.replace(/\r\n/g, '\n') ?? null;
      if (previous !== target.content) stale.push(relPath(target.path));
    }
    const phantom = await pruneStaleSkills(new Set(analyses.map((a) => a.service.name)), true);
    if (stale.length > 0 || phantom.length > 0) {
      if (phantom.length > 0) console.error(`Stale skill directories to remove: ${phantom.map((n) => `skills/${n}/`).join(', ')}`);
      if (stale.length > 0) {
        console.error('\nGenerated skills are stale:');
        for (const path of stale) console.error(`  ${path}`);
        console.error('\nRun: node scripts/generate-skills.ts');
      }
      process.exit(1);
    }
    console.log(
      `generated skills current: ${analyses.length} services, ${totalMethods} methods, ` +
        `${analyses.reduce((sum, a) => sum + pickExamples(a).length, 0)} examples`,
    );
    return;
  }

  let written = 0;
  for (const target of targets) {
    const previous = await readFile(target.path, 'utf8').catch(() => null);
    if (previous === target.content) continue;
    await mkdir(dirname(target.path), { recursive: true });
    await writeFile(target.path, target.content, 'utf8');
    written++;
    console.log(`wrote ${relPath(target.path)}`);
  }
  const removed = await pruneStaleSkills(new Set(analyses.map((a) => a.service.name)), false);
  for (const name of removed) console.log(`removed stale skills/${name}/`);

  console.log(
    `${analyses.length} services, ${totalMethods} methods, ` +
      `${targets.length - written} files unchanged, ${written} written` +
      (removed.length > 0 ? `, ${removed.length} removed` : ''),
  );
  const examples = analyses.reduce((sum, a) => sum + pickExamples(a).length, 0);
  console.log(`${examples} example commands derived for the ${analyses.length} service skills`);
}

main().catch((error: unknown) => {
  console.error(`generate-skills failed: ${error instanceof Error ? error.stack : String(error)}`);
  process.exit(1);
});
